"""Write the result macros and the ablation table of the paper from the result files.

Inputs:  results/report_test.json (report_test.py), results/ablation.json (ablation.py),
         results/test_pool_coverage.json (test_coverage.py)
Outputs: paper/tables/numbers.tex (\\newcommand macros quoted in the text)
         paper/tables/ablation_table.tex (Table V)
Usage: python make_tables.py
"""
import json

from common import ROOT

TABLES = ROOT.parent / 'paper' / 'tables'
SHORT = dict(SpanMatch='SM', SpanOverlapScore='SO', RevisionMatch='RM', RevisionSimilarity='RS', SoftMatch='Soft',
             ExactMatch='Exact')
COMPARISONS = {'selector - best hosted': 'Host', 'selector - top-beam BF16': 'BF',
               'selector - top-beam 4-bit': 'Four', 'selector - learner-only 4B': 'Learner',
               'selector - evidence-gated GPT-5.4': 'Gpt', 'selector - base top-beam': 'BaseTop',
               'selector - pool likelihood': 'PoolLL', 'pool likelihood - base top-beam': 'PoolLLBase',
               'selector - t5': 'Tfive', 'selector - deberta': 'Deberta', 'selector - local direct': 'LocDirect',
               'selector - local lgr': 'LocLgr'}
SUBSETS = dict(unseen_pair='Unseen', seen_pair='Seen', no_shared_unit='NoShared')
ROWS = [('full', 'Full selector'), ('fluency', 'Remove the fluency scores'),
        ('consistency', 'Remove the consistency features'), ('memory', 'Remove the development-count features'),
        ('guided', 'Remove the guided generator'), ('learned', 'Rank by mean likelihood only'),
        ('morph', 'Add the morphological variants'), ('zero_shot', 'Add a zero-shot Qwen3.5-4B generator')]


def gain(r):
    """Full selector minus variant (positive favors the full selector), with its simultaneous interval."""
    return -r['diff'], -r['sim'][1], -r['sim'][0]


def num(v, signed=False):
    text = f'{v:+.2f}' if signed else f'{v:.2f}'
    return text.replace('-', '$-$') if signed or v < 0 else text


def macro(name, value):
    return '\\newcommand{\\' + name + '}{' + value + '}'


def main():
    rep = json.load(open(ROOT / 'results' / 'report_test.json', encoding='utf-8'))
    lines = ['% Generated by exp/scripts/make_tables.py from results/report_test.json and results/ablation.json.']
    for metric, short in SHORT.items():
        lines.append(macro('Sel' + short, num(rep['selector'][metric])))
        lines.append(macro('HostBest' + short, num(rep['hosted'][rep['best_hosted']][metric])))
        lines.append(macro('TopFour' + short, num(rep['top_beam_4bit'][metric])))
        lines.append(macro('BaseTop' + short, num(rep['base_top'][metric])))
        lines.append(macro('GuidedTop' + short, num(rep['guided_top'][metric])))
        lines.append(macro('PoolLL' + short, num(rep['pool_likelihood'][metric])))
    for name, tag in [('Fine-tuned Japanese T5', 'Tfive'), ('DeBERTa localizer, base generator (4-bit)', 'Deberta'),
                      ('Direct prompting, local Qwen3-4B', 'LocDirect'), ('LGR-MAS, local Qwen3-4B', 'LocLgr')]:
        if name in rep.get('external', {}):
            for metric, short in SHORT.items():
                lines.append(macro(f'{tag}{short}', num(rep['external'][name][metric])))
    # Orthographic variants and the local acceptability judge (variant_match.py, acceptability_summary.py).
    var_path, acc_path = ROOT / 'results' / 'variant_match.json', ROOT / 'results' / 'acceptability_summary.json'
    if var_path.exists():
        var = json.load(open(var_path, encoding='utf-8'))
        lines.append(macro('VarSelExact', num(var['Category-guided selection']['variant_exact'])))
        c = var['Category-guided selection']['counts']
        lines.append(macro('VarSelCount', str(c.get('punctuation', 0) + c.get('reading', 0))))
    if acc_path.exists():
        acc = json.load(open(acc_path, encoding='utf-8'))
        lines.append(macro('JudgeTau', f"{acc['threshold']:.2f}"))
        for k, tag in [('reference', 'Ref'), ('source copy', 'Copy'), ('other reference', 'Swap')]:
            lines.append(macro(f'Judge{tag}', f"{acc['validation'][k]:.1f}"))
            lines.append(macro(f'JudgeCal{tag}', f"{acc['calibration'][k]:.1f}"))
        for sysname, tag in [('selector', 'Sel'), ('base_top', 'BaseTop'), ('local_lgr', 'LocLgr'), ('t5', 'Tfive')]:
            v = acc['systems'][sysname]
            lines.append(macro(f'Judge{tag}Mismatch', f"{v['mismatch']['accepted']:.1f}"))
            lines.append(macro(f'Judge{tag}MismatchN', f"{v['mismatch']['n']:,}"))
            lines.append(macro(f'Judge{tag}Exact', f"{v['exact']['accepted']:.1f}"))
    # Size of the largest deficit to the strongest hosted pipeline that the simultaneous CI still allows.
    lines.append(macro('DHostExactLoAbs', num(abs(rep['comparisons']['selector - best hosted']['ExactMatch']['sim'][0]))))
    seeds = rep['selector_seeds']
    lines.append(macro('SelExactSeeds', ', '.join(num(v) for v in seeds.values())))
    lines.append(macro('SelExactSeedMin', num(min(seeds.values()))))
    lines.append(macro('SelExactSeedMax', num(max(seeds.values()))))
    for key, tag in COMPARISONS.items():
        if key not in rep['comparisons']:
            continue
        for metric, short in SHORT.items():
            r = rep['comparisons'][key][metric]
            lines.append(macro(f'D{tag}{short}', num(r['diff'])))
            lines.append(macro(f'D{tag}{short}Lo', num(r['sim'][0])))
            lines.append(macro(f'D{tag}{short}Hi', num(r['sim'][1])))
    for key, tag in SUBSETS.items():
        s = rep['subsets'][key]
        lines.append(macro(f'N{tag}', str(s['n'])))
        for metric, short in SHORT.items():
            lines.append(macro(f'Sel{tag}{short}', num(s['selector'][metric])))
            lines.append(macro(f'Host{tag}{short}', num(s['best_hosted'][metric])))
            lines.append(macro(f'BF{tag}{short}', num(s['top_beam_bf16'][metric])))
            for comp, d in [('Host', s['diff_hosted']), ('BF', s['diff_bf16'])]:
                r = d[metric]
                lines.append(macro(f'D{comp}{tag}{short}', num(r['diff'])))
                lines.append(macro(f'D{comp}{tag}{short}Lo', num(r['sim'][0])))
                lines.append(macro(f'D{comp}{tag}{short}Hi', num(r['sim'][1])))
    cov = json.load(open(ROOT / 'results' / 'test_pool_coverage.json', encoding='utf-8'))
    for key, tag in [('full', 'Full'), ('no_guided', 'NoGuided')]:
        lines.append(macro(f'CovTest{tag}', f"{cov[key]['coverage']:.1f}"))
        lines.append(macro(f'PoolSize{tag}', f"{cov[key]['mean_pool_size']:.1f}"))
    lines.append(macro('CovTestFullSeeds', ', '.join(f'{v:.1f}' for v in cov['full']['per_seed'].values())))
    b = rep['both_span']
    lines += [macro('NBothSpan', str(b['n'])), macro('BothSpanSelRM', f"{b['selector_rm']:.1f}"),
              macro('BothSpanHostRM', f"{b['hosted_rm']:.1f}")]
    abl = json.load(open(ROOT / 'results' / 'ablation.json', encoding='utf-8'))
    # Control generators in place of the guided generator (controls_eval.py), placed after the removals.
    rows = list(ROWS)
    ctrl_path = ROOT / 'results' / 'controls.json'
    if ctrl_path.exists():
        ctrl = json.load(open(ctrl_path, encoding='utf-8'))
        names = dict(orig_k0_b='ctrl_base', guided_k0='ctrl_guidance', demos_k4='ctrl_demos')
        extra = []
        for k, v in ctrl.items():
            abl[names[k]] = v
            extra.append((names[k], v['label']))
        rows = ROWS[:6] + extra + ROWS[6:]
    for key, _ in rows:
        tag = ''.join(p.capitalize() for p in key.split('_'))
        lines.append(macro(f'Abl{tag}Dev', num(abl[key]['dev']['ExactMatch'])))
        if abl[key]['test'] is None:
            continue
        lines.append(macro(f'Abl{tag}Test', num(abl[key]['test']['ExactMatch'])))
        if key != 'full':
            r = abl[key]['diff_vs_full']['ExactMatch']
            d, lo, hi = gain(r)
            lines.append(macro(f'Abl{tag}D', num(d, signed=True)))
            lines.append(macro(f'Abl{tag}DLo', num(lo, signed=True)))
            lines.append(macro(f'Abl{tag}DHi', num(hi, signed=True)))
            lines.append(macro(f'Abl{tag}G', num(d)))  # unsigned forms for running text
            lines.append(macro(f'Abl{tag}GLo', num(lo)))
            lines.append(macro(f'Abl{tag}GHi', num(hi)))
    TABLES.mkdir(exist_ok=True)
    (TABLES / 'numbers.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')

    body = []
    last_control = [k for k, _ in rows if k.startswith('ctrl_')][-1:] or ['learned']
    for key, label in rows:
        if key in ('morph', 'zero_shot'):  # development-only additions, reported in the text
            continue
        a = abl[key]
        cells = [num(a['dev']['ExactMatch']), f"{a['dev_pool_coverage']:.1f}",
                 num(a['test']['ExactMatch']) if a['test'] else '--']
        if key == 'full' or a['test'] is None:
            cells.append('--')
        else:
            r = a['diff_vs_full']['ExactMatch']
            d, lo, hi = gain(r)
            cells.append(f"{num(d, signed=True)} ({num(lo)}, {num(hi)})")
        body.append(label + ' & ' + ' & '.join(cells) + ' \\\\')
        if key in ('full', 'learned') or key in last_control:
            body.append('\\midrule')
    tex = ('\\begin{table}[!t]\\centering\\footnotesize\n'
           '\\caption{Ablation of Category-Guided Selection (ExactMatch, \\%). Cov.\\ is the share of development '
           'examples whose pool contains the reference. The last column gives the test ExactMatch of the full selector minus that '
           'of the variant, with its six-metric simultaneous 95\\% CI; positive values favor the full selector. The second group refits '
           'the selector with a control generator in place of the guided generator}\n'
           '\\label{tab:ablation}\n\\setlength{\\tabcolsep}{4pt}\n'
           '\\begin{tabular}{@{}L{0.37\\columnwidth}rrrl@{}}\\toprule\n'
           'Configuration & Dev. & Cov. & Test & Full $-$ variant\\\\\\midrule\n'
           + '\n'.join(body[:-1] if body[-1] == '\\midrule' else body)
           + '\n\\bottomrule\\end{tabular}\n\\end{table}\n')
    (TABLES / 'ablation_table.tex').write_text(tex, encoding='utf-8')
    print('wrote', TABLES / 'numbers.tex', TABLES / 'ablation_table.tex')


if __name__ == '__main__':
    main()
